CREATE INDEX IF NOT EXISTS problems_current_idx ON problems (is_current, problem_type);
CREATE INDEX IF NOT EXISTS problems_archive_idx ON problems (is_archived, release_date DESC);
CREATE INDEX IF NOT EXISTS submissions_user_idx ON submissions (user_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS submissions_problem_idx ON submissions (problem_id);
CREATE INDEX IF NOT EXISTS proposals_status_idx ON problem_proposals (status, created_at DESC);
CREATE INDEX IF NOT EXISTS hint_requests_status_idx ON hint_requests (status, created_at DESC);
